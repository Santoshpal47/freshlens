"""Write docs/findings.md straight from the gold marts, so no number in it is typed by hand."""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

from pyspark.sql import SparkSession
from pyspark.sql import functions as F

from freshlens.config import PROJECT_ROOT, Settings


def _md_table(rows: list[dict], cols: list[str]) -> str:
    if not rows:
        return "_no rows yet_\n"
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join("" if r[c] is None else str(r[c]) for c in cols) + " |" for r in rows]
    return "\n".join(out) + "\n"


def write_findings(spark: SparkSession, settings: Settings, out: Path | None = None) -> Path:
    def t(name: str):
        return spark.read.format("delta").load(settings.table("gold", name))

    out = out or PROJECT_ROOT / "docs" / "findings.md"
    silver = spark.read.format("delta").load(settings.table("silver", "prices"))
    cov = silver.agg(
        F.count("*").alias("rows"), F.min("arrival_date").alias("first"), F.max("arrival_date").alias("last")
    ).first()

    spread = [
        r.asDict()
        for r in t("mart_sourcing_spread")
        .groupBy("lane")
        .agg(
            F.count("*").alias("days_compared"),
            F.min("date").alias("from"),
            F.max("date").alias("to"),
            F.round(F.avg(F.col("direct_sourcing_cheaper").cast("double")) * 100, 1).alias(
                "direct_cheaper_pct_of_days"
            ),
            F.round(F.percentile_approx("spread_kg", 0.5), 2).alias("median_spread_rs_kg"),
        )
        .orderBy("lane")
        .collect()
    ]

    weekly = [
        r.asDict() for r in t("mart_lead_lag_weekly").where("lag_weeks <= 2").orderBy("lane", "lag_weeks").collect()
    ]
    daily_best = (
        t("mart_lead_lag").groupBy("lane").agg(F.round(F.max("corr"), 3).alias("max_daily_corr")).orderBy("lane")
    )
    daily = [r.asDict() for r in daily_best.collect()]
    backtest = [r.asDict() for r in t("mart_alert_backtest").orderBy("lane").collect()]
    vol = [
        r.asDict()
        for r in t("mart_volatility")
        .where("market = 'Azadpur' AND log_return IS NOT NULL")
        .groupBy("commodity")
        .agg(
            F.count("*").alias("daily_returns"),
            F.round(F.stddev("log_return") * 100, 2).alias("daily_vol_pct"),
            F.round(F.percentile_approx("vol_30d_pct", 0.9), 2).alias("p90_30d_vol_pct"),
        )
        .orderBy(F.desc("daily_vol_pct"))
        .collect()
    ]

    md = f"""# Findings

_Generated by `freshlens report` on {datetime.now():%Y-%m-%d %H:%M} from the gold marts. Do not edit by hand._

Coverage: **{cov["rows"]:,} silver rows**, arrival dates {cov["first"]} → {cov["last"]}.
If a lane below has few days compared, its history is not fully downloaded yet (`freshlens backfill` resumes).

## 1. Volatility at Azadpur (stdev of daily log-returns)

{_md_table(vol, ["commodity", "daily_returns", "daily_vol_pct", "p90_30d_vol_pct"])}
## 2. Is buying at the source mandi cheaper? (spread = Delhi − source − freight)

{_md_table(spread, ["lane", "days_compared", "from", "to", "direct_cheaper_pct_of_days", "median_spread_rs_kg"])}
Freight per kg is an assumption in `config/settings.yaml`, so every spread moves one-for-one with it.

## 3. Does the source lead Delhi?

Day-to-day, barely. The best daily correlation of returns at any lag from 0 to 10 days:

{_md_table(daily, ["lane", "max_daily_corr"])}
Daily quotes are noisy (arrival mix, grade, missing days). On **weekly medians** the link shows up:

{_md_table(weekly, ["lane", "lag_weeks", "corr", "n_weeks", "reliable"])}
`reliable` = at least {settings.analysis["weekly_min_overlap_weeks"]} paired weeks and corr ≥ {
        settings.analysis["min_corr"]
    }.

## 4. Back-test: source up ≥{settings.analysis["spike_threshold_pct"]}% this week → Delhi up next week?

{
        _md_table(
            backtest,
            [
                "lane",
                "n_spikes",
                "hit_rate_pct",
                "base_rate_up_pct",
                "avg_delhi_next_week_after_spike_pct",
                "avg_delhi_next_week_all_pct",
            ],
        )
    }
The rule only adds value where `hit_rate_pct` is clearly above `base_rate_up_pct` with a meaningful `n_spikes`.
"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(md)
    return out
